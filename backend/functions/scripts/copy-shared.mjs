// Firebase deploys functions/ standalone (it is NOT an npm workspace member), so it cannot import
// @p6/shared. This copies the pure shared modules (types, game rules, callable contract) from packages/shared
// into src/shared. Runs automatically before `build`, `typecheck` and `test`. src/shared is generated and git-ignored.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const from = path.resolve(here, "../../../packages/shared/src");
const to = path.resolve(here, "../src/shared");
const FILES = ["types", "gameRules", "api", "stars", "progress", "answer", "names", "classroom", "admin"]; // answer.ts: the server marks answers itself
fs.mkdirSync(to, { recursive: true });
for (const f of FILES) {
  let src = fs.readFileSync(path.join(from, `${f}.ts`), "utf8");
  // NodeNext resolution needs explicit extensions on relative imports.
  src = src.replace(/from "\.\/(\w+)"/g, 'from "./$1.js"');
  fs.writeFileSync(path.join(to, `${f}.ts`), `// GENERATED by scripts/copy-shared.mjs from packages/shared/src/${f}.ts. Do not edit.\n${src}`);
}
fs.writeFileSync(path.join(to, "index.ts"), FILES.map((f) => `export * from "./${f}.js";`).join("\n") + "\n");
console.log("copied shared → src/shared");

// The editor-doc → Question transform of the content pipeline (pure: no Node/sharp/fs), so getQuestionPatches converts an
// edited doc exactly as the bundle build does. Generated into src/question (git-ignored); imports re-pointed at ./shared.
const qFrom = path.resolve(here, "../../../content/src");
const qTo = path.resolve(here, "../src/question");
fs.mkdirSync(qTo, { recursive: true });
for (const f of ["question", "answerSpec", "tokenizer"]) {
  let src = fs.readFileSync(path.join(qFrom, `${f}.ts`), "utf8");
  src = src.replace(/from "@p6\/shared"/g, 'from "../shared/index.js"').replace(/from "\.\/(\w+)"/g, 'from "./$1.js"');
  fs.writeFileSync(path.join(qTo, `${f}.ts`), `// GENERATED by scripts/copy-shared.mjs from content/src/${f}.ts. Do not edit.\n${src}`);
}
console.log("copied content transform → src/question");

// The server marks level and mini-game answers itself (a modified app or a direct API call can't claim stars for
// wrong answers), so it needs the answers: extracted from the app's question bundle into src/content (generated,
// git-ignored), with each level's questions. Only what marking needs: MCQ key or the parts' answer specs.
const appContent = path.resolve(here, "../../../apps/mobile/assets/content");
const contentOut = path.resolve(here, "../src/content");
fs.mkdirSync(contentOut, { recursive: true });
const grades = {};
/** Same function as logic/patches.ts figHash: short hash of a figure_url (the url itself is not needed server side). */
const figHash = (url) => crypto.createHash("sha1").update(url).digest("hex").slice(0, 10);
for (const grade of fs.readdirSync(appContent).filter((g) => /^P[4-6]$/.test(g))) {
  const qfile = path.join(appContent, grade, "questions.json"), cfile = path.join(appContent, grade, "curriculum.json");
  if (!fs.existsSync(qfile) || !fs.existsSync(cfile)) continue;
  const { version, builtAt, questions } = JSON.parse(fs.readFileSync(qfile, "utf8"));
  // source-info.json (written by the content build): when the editor snapshot was read, the figure_url each bundled figure
  // came from, and the editor's picks. Optional: without it patches still work (no figure change detection).
  const sfile = path.join(appContent, grade, "source-info.json");
  const info = fs.existsSync(sfile) ? JSON.parse(fs.readFileSync(sfile, "utf8")) : {};
  const picked = new Set(info.selected ?? []);
  const curriculum = JSON.parse(fs.readFileSync(cfile, "utf8"));
  const answers = {};
  for (const q of Object.values(questions)) {
    if (!q.autoMarkable) continue;
    answers[q.id] = q.type === "mcq" ? { t: "mcq", o: q.correctOption ?? "" } : { t: "open", p: (q.parts ?? []).map((x) => x.answer) };
  }
  // Per bundled question, what getQuestionPatches needs to rebuild it from the editor doc: subtopic (index into
  // `subtopics`), canonical topic, difficulty number, figure present (f), figure source hash (u), editor pick at build (p).
  const subtopics = [], subIx = new Map(), meta = {};
  for (const q of Object.values(questions)) {
    if (!subIx.has(q.subtopicId)) { subIx.set(q.subtopicId, subtopics.length); subtopics.push(q.subtopicId); }
    const m = { s: subIx.get(q.subtopicId), c: q.topic, d: Number(q.difficulty.slice(2)) };
    if (q.figure) { m.f = 1; if (info.figureSources?.[q.id]) m.u = figHash(info.figureSources[q.id]); }
    if (picked.has(q.id)) m.p = 1;
    meta[q.id] = m;
  }
  const levels = {};
  for (const t of curriculum.topics) for (const st of t.subtopics) for (const lv of [1, 2, 3]) levels[`${st.id}#${lv}`] = st.main?.[lv] ?? [];
  // Each topic's subtopic ids in map order (friends' map spots: every Level 1, then every Level 2, then every Level 3).
  // `name` + `names` (subtopic id → name): titles for classroom worksheets, milestone posts and analytics.
  const names = {};
  for (const t of curriculum.topics) for (const st of t.subtopics) names[st.id] = st.name;
  const topics = [...curriculum.topics].sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
    .map((t) => ({ id: t.id, name: t.name, subtopics: [...t.subtopics].sort((a, b) => (a.order ?? 0) - (b.order ?? 0)).map((st) => st.id) }));
  grades[grade] = { version, builtAt, snapshotAt: info.snapshotAt || builtAt, levels, answers, topics, names, subtopics, questions: meta };
}
fs.writeFileSync(path.join(contentOut, "index.ts"), `// GENERATED by scripts/copy-shared.mjs from apps/mobile/assets/content. Do not edit.
import type { AnswerSpec } from "../shared/index.js";

export interface ServerQuestion { t: "mcq" | "open"; o?: string; p?: AnswerSpec[] }
export interface ServerContent {
  version: string;
  /** QuestionBundle.builtAt */
  builtAt: string;
  /** when the editor snapshot the bundle was built from was read (<= builtAt); edits after it are not in the bundle */
  snapshotAt: string;
  /** \`\${subtopicId}#\${level}\` → the level's question ids */
  levels: Record<string, string[]>;
  /** auto-markable questions → what marking needs */
  answers: Record<string, ServerQuestion>;
  /** topics by \`order\`, each with its subtopic ids by \`order\` */
  topics: { id: string; name: string; subtopics: string[] }[];
  /** subtopic id → name */
  names: Record<string, string>;
  /** subtopic ids; QuestionMeta.s indexes into this */
  subtopics: string[];
  /** every bundled question → what getQuestionPatches needs to rebuild it from the editor doc */
  questions: Record<string, QuestionMeta>;
}
export interface QuestionMeta {
  s: number; // index into ServerContent.subtopics
  c: string; // canonical topic
  d: 1 | 2 | 3; // difficulty
  f?: 1; // the bundle has a figure image for it
  u?: string; // sha1[0..10] of the editor figure_url the image came from (absent: unknown)
  p?: 1; // the editor had it selected at build time
}
export const CONTENT: Record<string, ServerContent | undefined> = ${JSON.stringify(grades)};
`);
console.log(`content → src/content (${Object.entries(grades).map(([g, c]) => `${g}: ${Object.keys(c.answers).length} answers, version ${c.version}`).join("; ")})`);
