// The backend compiles to CommonJS with NodeNext resolution, so it can't import the TypeScript sources of @p6/shared.
// This copies the pure shared modules it needs (Catapult Classroom contract) into src/shared (generated, git-ignored).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const from = path.resolve(here, "../../packages/shared/src");
const to = path.resolve(here, "../src/shared");
const FILES = ["types", "lessons"];
fs.mkdirSync(to, { recursive: true });
for (const f of FILES) {
  const src = fs.readFileSync(path.join(from, `${f}.ts`), "utf8").replace(/from "\.\/(\w+)"/g, 'from "./$1.js"');
  fs.writeFileSync(path.join(to, `${f}.ts`), `// GENERATED by scripts/copy-shared.mjs from packages/shared/src/${f}.ts. Do not edit.\n${src}`);
}
fs.writeFileSync(path.join(to, "index.ts"), FILES.map((f) => `export * from "./${f}.js";`).join("\n") + "\n");
console.log("copied shared → src/shared");
