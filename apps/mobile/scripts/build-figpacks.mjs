// Packs each grade's question figures into a few big files so an app update ships ~10 assets instead of ~1,600
// (EAS Update allows at most 1000 assets per update).
//
//   node scripts/build-figpacks.mjs [--force]      (run by `postinstall`, and by the content pipeline)
//
// Input : assets/content/<grade>/figures/*.webp   (+ figures/manifest.json: question figure id -> file name)
// Output: assets/content/<grade>/figpacks/pack-<n>.figpack   (the .webp files joined end to end, unchanged)
//         assets/content/<grade>/figpacks/registry.ts        (requires the packs; id -> [pack, offset, length, w, h])
// Everything in figpacks/ is a build output (gitignored). The run is skipped when a hash of the inputs matches.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const PACK_LIMIT = 12 * 1024 * 1024; // bytes per pack file
const FORMAT_VERSION = "1"; // bump to force a rebuild when the output format changes
const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DEFAULT_CONTENT_ROOT = path.resolve(HERE, "..", "assets", "content");

/** Pixel size of a WebP file from its header (VP8 lossy, VP8L lossless, VP8X extended). Throws on anything else. */
export function parseWebpSize(buf) {
  if (buf.length < 30 || buf.toString("latin1", 0, 4) !== "RIFF" || buf.toString("latin1", 8, 12) !== "WEBP") {
    throw new Error("not a WebP file");
  }
  const kind = buf.toString("latin1", 12, 16);
  if (kind === "VP8 ") {
    if (buf[23] !== 0x9d || buf[24] !== 0x01 || buf[25] !== 0x2a) throw new Error("bad VP8 start code");
    return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  }
  if (kind === "VP8L") {
    if (buf[20] !== 0x2f) throw new Error("bad VP8L signature");
    const bits = buf.readUInt32LE(21);
    return { width: (bits & 0x3fff) + 1, height: ((bits >>> 14) & 0x3fff) + 1 };
  }
  if (kind === "VP8X") {
    return { width: buf.readUIntLE(24, 3) + 1, height: buf.readUIntLE(27, 3) + 1 };
  }
  throw new Error(`unknown WebP chunk "${kind}"`);
}

/**
 * Splits figures (already sorted by id) into packs. Pure: used by the build and by the tests.
 * @param {{id: string, data: Buffer}[]} figs
 * @returns {{packs: Buffer[], index: Record<string, [number, number, number, number, number]>}}
 */
export function packFigures(figs, limit = PACK_LIMIT) {
  const packs = [];
  const index = {};
  let parts = [];
  let size = 0;
  const flush = () => {
    if (size) packs.push(Buffer.concat(parts));
    parts = [];
    size = 0;
  };
  for (const { id, data } of figs) {
    if (size && size + data.length > limit) flush();
    const { width, height } = parseWebpSize(data);
    index[id] = [packs.length, size, data.length, width, height];
    parts.push(data);
    size += data.length;
  }
  flush();
  return { packs, index };
}

function readManifest(figDir, files) {
  const mp = path.join(figDir, "manifest.json");
  if (fs.existsSync(mp)) return JSON.parse(fs.readFileSync(mp, "utf8")); // id -> file name
  return Object.fromEntries(files.map((f) => [f.replace(/\.webp$/, ""), f])); // fallback: id = file stem
}

function registrySource(hash, packCount, index) {
  const requires = Array.from({ length: packCount }, (_, i) => `  require("./pack-${i}.figpack") as number,`).join("\n");
  return `// GENERATED by scripts/build-figpacks.mjs (postinstall + content pipeline). Gitignored, do not edit.
/* eslint-disable @typescript-eslint/no-require-imports */
/** Changes whenever any figure changes; names the on-device folder the figures are extracted to. */
export const hash = ${JSON.stringify(hash)};
export const packs: number[] = [
${requires}
];
/** figure id -> [pack number, byte offset, byte length, width, height] */
export const index: Record<string, readonly [number, number, number, number, number]> = ${JSON.stringify(index)};
`;
}

/** Builds figpacks/ for one grade. Returns { built, figures, packs, bytes, hash }. */
export function buildGrade(contentRoot, grade, { force = false } = {}) {
  const figDir = path.join(contentRoot, grade, "figures");
  const outDir = path.join(contentRoot, grade, "figpacks");
  if (!fs.existsSync(figDir)) return null;
  const files = fs.readdirSync(figDir).filter((f) => f.endsWith(".webp")).sort();
  const manifest = readManifest(figDir, files);
  const ids = Object.keys(manifest).sort();

  const h = crypto.createHash("sha1").update(`${FORMAT_VERSION}\n${PACK_LIMIT}\n`);
  const figs = ids.map((id) => {
    const data = fs.readFileSync(path.join(figDir, manifest[id]));
    h.update(`${id}\0${manifest[id]}\0${data.length}\0`).update(data);
    return { id, data };
  });
  const hash = h.digest("hex").slice(0, 12);

  const stamp = path.join(outDir, ".inputs");
  const registryPath = path.join(outDir, "registry.ts");
  if (!force && fs.existsSync(stamp) && fs.readFileSync(stamp, "utf8") === hash && fs.existsSync(registryPath)) {
    const m = fs.readFileSync(registryPath, "utf8").match(/pack-\d+\.figpack/g) ?? [];
    if (m.every((p) => fs.existsSync(path.join(outDir, p)))) return { built: false, figures: ids.length, packs: m.length, hash };
  }

  const { packs, index } = packFigures(figs);
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  packs.forEach((p, i) => fs.writeFileSync(path.join(outDir, `pack-${i}.figpack`), p));
  fs.writeFileSync(registryPath, registrySource(hash, packs.length, index));
  fs.writeFileSync(stamp, hash);
  return { built: true, figures: ids.length, packs: packs.length, bytes: packs.reduce((a, p) => a + p.length, 0), hash };
}

/** Builds the packs of every grade that has figures. */
export function buildFigpacks({ contentRoot = DEFAULT_CONTENT_ROOT, force = false } = {}) {
  if (!fs.existsSync(contentRoot)) return {};
  const out = {};
  for (const grade of fs.readdirSync(contentRoot).sort()) {
    const r = buildGrade(contentRoot, grade, { force });
    if (r) out[grade] = r;
  }
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const t = Date.now();
  const res = buildFigpacks({ force: process.argv.includes("--force") });
  for (const [g, r] of Object.entries(res)) {
    console.log(`figpacks ${g}: ${r.built ? "built" : "up to date"} (${r.figures} figures, ${r.packs} packs, hash ${r.hash}) ${Date.now() - t}ms`);
  }
}
